-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT property.ID AS ENTITY_ID, property.NAME AS ENTITY_NAME,
       property.REGION, property.CATEGORY, property.RISK_TIER, property.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.ROOM_NIGHTS) AS ROOM_NIGHTS,
       SUM(observation.ROOM_REVENUE_THB) AS ROOM_REVENUE_THB,
       SUM(observation.PACE_FLAG_COUNT) AS PACE_FLAG_COUNT,
       SUM(observation.SELLOUT_COUNT) AS SELLOUT_COUNT,
       SUM(observation.ALLOTMENT_RECALL) AS RECALL_COUNT,
       SUM(observation.PICKUP_REVIEW_DUE) AS PICKUP_REVIEW_DUE,
       SUM(observation.PICKUP_REVIEW_DONE) AS PICKUP_REVIEW_DONE,
       100.0 * COUNT_IF(observation.PACE_FLAG_COUNT = 0) / NULLIF(COUNT(*), 0) AS FLAG_FREE_DAY_PCT,
       100.0 * SUM(observation.SELLOUT_COUNT) / NULLIF(SUM(observation.PACE_FLAG_COUNT), 0) AS FLAG_SELLOUT_PCT,
       100.0 * SUM(observation.PICKUP_REVIEW_DONE) / NULLIF(SUM(observation.PICKUP_REVIEW_DUE), 0) AS PICKUP_REVIEW_PCT,
       AVG(observation.FORECAST_ERROR_PCT) AS AVG_FORECAST_ERROR_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.PROPERTY_DAILY observation
JOIN RAW.HOTEL_PROPERTIES property ON property.ID = observation.ENTITY_ID
GROUP BY property.ID, property.NAME, property.REGION, property.CATEGORY, property.RISK_TIER, property.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(ROOM_NIGHTS) AS ROOM_NIGHTS, SUM(ROOM_REVENUE_THB) AS ROOM_REVENUE_THB,
       SUM(PACE_FLAG_COUNT) AS PACE_FLAG_COUNT, SUM(SELLOUT_COUNT) AS SELLOUT_COUNT,
       100.0 * SUM(SELLOUT_COUNT) / NULLIF(SUM(PACE_FLAG_COUNT), 0) AS FLAG_SELLOUT_PCT
FROM RAW.PROPERTY_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.PACE_FLAG_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT PACE_FLAG_TYPE, SUM(PACE_FLAG_COUNT) AS PACE_FLAG_COUNT,
       SUM(SELLOUT_COUNT) AS SELLOUT_COUNT,
       SUM(ALLOTMENT_RECALL) AS RECALL_COUNT,
       SUM(ROOM_REVENUE_THB) AS EXPOSED_REVENUE_THB,
       100.0 * SUM(SELLOUT_COUNT) / NULLIF(SUM(PACE_FLAG_COUNT), 0) AS FLAG_SELLOUT_PCT
FROM RAW.PROPERTY_DAILY
WHERE PACE_FLAG_COUNT > 0
GROUP BY PACE_FLAG_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(ROOM_NIGHTS) AS NIGHTS, SUM(PACE_FLAG_COUNT) AS FLAGS, COUNT(*) AS PROPERTY_DAYS, COUNT_IF(PACE_FLAG_COUNT = 0) AS FREE_DAYS,
         SUM(SELLOUT_COUNT) AS SELLOUTS, SUM(ALLOTMENT_RECALL) AS RECALLS, SUM(ROOM_REVENUE_THB) AS ROOM_REVENUE_THB,
         SUM(PICKUP_REVIEW_DUE) AS PICKUP_REVIEW_DUE, SUM(PICKUP_REVIEW_DONE) AS PICKUP_REVIEW_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.PROPERTY_DAILY
), book AS (SELECT COUNT(*) AS PROPERTY_COUNT FROM RAW.HOTEL_PROPERTIES),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.ALLOTMENT_CONFIRMATIONS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Flag-Free Day Rate' AS TITLE,
         100.0 * FREE_DAYS / NULLIF(PROPERTY_DAYS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Pace Flags Raised', FLAGS, '' FROM observations
  UNION ALL SELECT 3, 'Early Sell-outs', SELLOUTS, '' FROM observations
  UNION ALL SELECT 4, 'Flag Sell-out Rate', 100.0 * SELLOUTS / NULLIF(FLAGS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Allotment Recalls', RECALLS, '' FROM observations
  UNION ALL SELECT 6, 'Room Revenue (THB M)', ROOM_REVENUE_THB / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Room Nights Sold', NIGHTS, '' FROM observations
  UNION ALL SELECT 8, 'Pickup Review Adherence', 100.0 * PICKUP_REVIEW_DONE / NULLIF(PICKUP_REVIEW_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Properties Monitored', PROPERTY_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Allotment Confirmation Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Allotment Confirmations Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.PACE_FLAG_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
