-- Early sell-out risk scoring and network room-night forecast over the synthetic snapshot.
-- Predicts P(early sell-out at the property in the next 7 days) per property and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.SELLOUT_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, a.CATEGORY, a.RISK_TIER, a.PROPERTY_AGE_YEARS,
       r.FORECAST_ERROR_PCT, r.RATE_RESPONSE_HRS,
       AVG(r.FORECAST_ERROR_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS FORECAST_ERROR_7D,
       SUM(r.SELLOUT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS SELLOUT_30D,
       IFF(SUM(r.SELLOUT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'SELLOUT', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.PROPERTY_DAILY r JOIN RAW.HOTEL_PROPERTIES a ON a.ID = r.ENTITY_ID
-- Flight disruptions are destination-wide, not property-driven, so they are excluded from training.
WHERE r.PACE_FLAG_TYPE <> 'Flight disruption';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.SELLOUT_TRAIN AS
SELECT CATEGORY, RISK_TIER, PROPERTY_AGE_YEARS, FORECAST_ERROR_PCT, RATE_RESPONSE_HRS, FORECAST_ERROR_7D, SELLOUT_30D, LABEL
FROM ML.SELLOUT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.SELLOUT_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, PROPERTY_AGE_YEARS, FORECAST_ERROR_PCT, RATE_RESPONSE_HRS, FORECAST_ERROR_7D, SELLOUT_30D, LABEL
FROM ML.SELLOUT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.SELLOUT_RISK_MODEL(
  INPUT_DATA => TABLE(ML.SELLOUT_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.SELLOUT_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.SELLOUT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'PROPERTY_AGE_YEARS', PROPERTY_AGE_YEARS,
           'FORECAST_ERROR_PCT', FORECAST_ERROR_PCT, 'RATE_RESPONSE_HRS', RATE_RESPONSE_HRS,
           'FORECAST_ERROR_7D', FORECAST_ERROR_7D, 'SELLOUT_30D', SELLOUT_30D)):probability:SELLOUT::FLOAT AS P
  FROM ML.SELLOUT_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'SELLOUT', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'SELLOUT', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'SELLOUT', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'SELLOUT', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per property (label unknown, so excluded from features).
CREATE TABLE ML.SELLOUT_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.SELLOUT_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.SELLOUT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'PROPERTY_AGE_YEARS', PROPERTY_AGE_YEARS,
           'FORECAST_ERROR_PCT', FORECAST_ERROR_PCT, 'RATE_RESPONSE_HRS', RATE_RESPONSE_HRS,
           'FORECAST_ERROR_7D', FORECAST_ERROR_7D, 'SELLOUT_30D', SELLOUT_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:SELLOUT::FLOAT, 4) AS SELLOUT_PROB_7D,
       CASE WHEN P:probability:SELLOUT::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:SELLOUT::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide room-night forecast (14 days) from the daily series, for revenue planning.
CREATE VIEW ML.DAILY_ROOM_NIGHTS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(ROOM_NIGHTS)::FLOAT AS ROOM_NIGHTS
FROM RAW.PROPERTY_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.ROOM_NIGHT_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_ROOM_NIGHTS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'ROOM_NIGHTS'
);

CREATE TABLE ML.ROOM_NIGHT_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS ROOM_NIGHTS,       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.ROOM_NIGHT_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
